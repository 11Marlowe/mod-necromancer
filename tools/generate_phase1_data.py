#!/usr/bin/env python3
"""Generate the Necromancer Phase-1 world SQL from an existing Turtle DB.

The class reuses the closest caster chassis per race (Warlock where the race
has one, otherwise Priest) for position / starting kit / racial spells, drops
the source class's own spells, and adds the Necromancer's own stat descriptor
(a Warlock-like caster for now; tunable later via `class_descriptor`).

Usage:
  python tools/generate_phase1_data.py --out data/sql/world/20261014150000_world.sql
  python tools/generate_phase1_data.py --mariadb <path> --port 3307

(--out writes UTF-8 directly; do not use PowerShell ">" which writes UTF-16.)
"""

import argparse
import subprocess
import sys

CLASS_NECROMANCER = 10
RACES = list(range(1, 11))          # 1..8 vanilla + Goblin(9) + High Elf(10)
SOURCE_CLASS = {r: 9 for r in RACES}   # Warlock chassis
SOURCE_CLASS[4] = 5                    # Night Elf: no warlock
SOURCE_CLASS[6] = 5                    # Tauren: no warlock
SOURCE_CLASS[10] = 5                   # High Elf: no warlock

# Spells of the source class that must NOT be granted to the Necromancer.
SOURCE_CLASS_SPELLS = {
    9: {686, 687},     # Shadow Bolt, Demon Skin
    5: {585, 2050},    # Smite, Lesser Heal
}

# Extra weapon skill the Necromancer starts with (design: staves).
EXTRA_SPELLS = [
    (227, "Staves"),
]


def query(mariadb, port, sql):
    out = subprocess.run(
        [mariadb, f"--port={port}", "-u", "root", "tw_world",
         "--batch", "--skip-column-names", "-e", sql],
        capture_output=True, text=True, check=True,
    )
    rows = []
    for line in out.stdout.splitlines():
        line = line.rstrip("\r")
        if not line:
            continue
        rows.append(line.split("\t"))
    return rows


def sql_escape(s):
    return s.replace("\\", "\\\\").replace("'", "''")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mariadb", default=r"C:\Users\gawrg\Desktop\TurtleTest\server\mariadb-portable\bin\mariadb.exe")
    ap.add_argument("--port", default="3307")
    ap.add_argument("--out", help="write UTF-8 SQL to this file instead of stdout")
    args = ap.parse_args()

    q = lambda sql: query(args.mariadb, args.port, sql)

    positions = q("SELECT race, class, map, zone, position_x, position_y, position_z, orientation "
                  "FROM playercreateinfo WHERE class IN (5,9)")
    spells = q("SELECT race, class, spell, IFNULL(note,'') FROM playercreateinfo_spell "
               "WHERE class IN (5,9) ORDER BY race, class, spell")
    items = q("SELECT DISTINCT race, class, itemid, amount FROM playercreateinfo_item "
              "WHERE class IN (5,9) ORDER BY race, class, itemid")
    actions = q("SELECT DISTINCT race, class, button, action, type FROM playercreateinfo_action "
                "WHERE class IN (5,9) ORDER BY race, class, button")
    classstats = q("SELECT level, basehp, basemana FROM player_classlevelstats WHERE class=9 ORDER BY level")
    levelstats = q("SELECT race, class, level, str, agi, sta, inte, spi FROM player_levelstats "
                   "WHERE class IN (5,9) ORDER BY race, class, level")

    # Index source rows by (race, source class)
    pos = {(int(r[0]), int(r[1])): r for r in positions}
    spi = {}
    for r in spells:
        spi.setdefault((int(r[0]), int(r[1])), []).append(r)
    itm = {}
    for r in items:
        itm.setdefault((int(r[0]), int(r[1])), []).append(r)
    act = {}
    for r in actions:
        act.setdefault((int(r[0]), int(r[1])), []).append(r)
    lvl = {}
    for r in levelstats:
        lvl.setdefault((int(r[0]), int(r[1])), []).append(r)

    out = []
    w = out.append
    w("-- FILE: 20261014150000_world.sql")
    w("-- Necromancer (class 10) Phase 1 identity data, generated by")
    w("-- tools/generate_phase1_data.py.  Re-runnable: deletes class-10 rows first.")
    w("--")
    w("-- Chassis: per-race Warlock data where available (Night Elf, Tauren and")
    w("-- High Elf use Priest), minus the source class spells, plus Staves; stats")
    w("-- use the Warlock curves; class_descriptor mirrors Warlock until balancing.")
    w("")
    w("DELETE FROM `playable_class` WHERE `id` = 10;")
    w("DELETE FROM `class_descriptor` WHERE `class` = 10;")
    w("DELETE FROM `playercreateinfo` WHERE `class` = 10;")
    w("DELETE FROM `player_classlevelstats` WHERE `class` = 10;")
    w("DELETE FROM `player_levelstats` WHERE `class` = 10;")
    w("DELETE FROM `playercreateinfo_spell` WHERE `class` = 10;")
    w("DELETE FROM `playercreateinfo_item` WHERE `class` = 10;")
    w("DELETE FROM `playercreateinfo_action` WHERE `class` = 10;")
    w("")

    w("-- Enables the class for the player-info loaders.")
    w("INSERT INTO `playable_class` (`id`, `comment`) VALUES (10, 'Necromancer');")
    w("")
    w("-- Stat formulas (Warlock-like caster chassis; NULL = built-in default).")
    w("INSERT INTO `class_descriptor`")
    w("  (`class`, `ap_melee_level`, `ap_melee_str`, `ap_melee_agi`, `ap_melee_flat`,")
    w("   `ap_ranged_level`, `ap_ranged_str`, `ap_ranged_agi`, `ap_ranged_flat`,")
    w("   `base_crit`, `base_dodge`,")
    w("   `melee_crit_agi_level1`, `melee_crit_agi_level60`,")
    w("   `dodge_agi_level1`, `dodge_agi_level60`,")
    w("   `spell_crit_base`, `spell_crit_rate0`, `spell_crit_rate1`,")
    w("   `hp_per_spirit`, `hp_regen_flat`, `mp_spirit_divisor`, `mp_regen_flat`,")
    w("   `caster_default`)")
    w("VALUES")
    w("  (10, 0, 1, 0, -10,  0, 0, 1, -10,  2.0, 2.0,  8.4, 20.0,  8.4, 20.0,")
    w("   3.18, 11.30, 0.82,  0.12, 1.5, 5, 15,  1);")
    w("")

    w("-- Starting position per race (from the chassis class).")
    w("INSERT INTO `playercreateinfo`")
    w("  (`race`, `class`, `map`, `zone`, `position_x`, `position_y`, `position_z`, `orientation`) VALUES")
    rows = []
    for race in RACES:
        r = pos[(race, SOURCE_CLASS[race])]
        rows.append(f"  ({race}, 10, {r[2]}, {r[3]}, {r[4]}, {r[5]}, {r[6]}, {r[7]})")
    w(",\n".join(rows) + ";")
    w("")

    w("-- Base health/mana per level (Warlock curve).")
    w("INSERT INTO `player_classlevelstats` (`class`, `level`, `basehp`, `basemana`) VALUES")
    rows = [f"  (10, {r[0]}, {r[1]}, {r[2]})" for r in classstats]
    w(",\n".join(rows) + ";")
    w("")

    w("-- Stat growth per race/level (chassis class curves).")
    w("INSERT INTO `player_levelstats` (`race`, `class`, `level`, `str`, `agi`, `sta`, `inte`, `spi`) VALUES")
    rows = []
    for race in RACES:
        for r in lvl[(race, SOURCE_CLASS[race])]:
            rows.append(f"  ({race}, 10, {r[2]}, {r[3]}, {r[4]}, {r[5]}, {r[6]}, {r[7]})")
    w(",\n".join(rows) + ";")
    w("")

    w("-- Starting spells: chassis racials/languages/weapon skills, minus the")
    w("-- chassis class spells, plus Staves.")
    w("INSERT INTO `playercreateinfo_spell` (`race`, `class`, `spell`, `note`) VALUES")
    rows = []
    for race in RACES:
        src = SOURCE_CLASS[race]
        drop = SOURCE_CLASS_SPELLS[src]
        for r in spi[(race, src)]:
            spell = int(r[2])
            if spell in drop:
                continue
            rows.append(f"  ({race}, 10, {spell}, '{sql_escape(r[3])}')")
        for spell, note in EXTRA_SPELLS:
            rows.append(f"  ({race}, 10, {spell}, '{note}')")
    w(",\n".join(rows) + ";")
    w("")

    w("-- Starting items (chassis kit).")
    w("INSERT INTO `playercreateinfo_item` (`race`, `class`, `itemid`, `amount`) VALUES")
    rows = []
    for race in RACES:
        for r in itm[(race, SOURCE_CLASS[race])]:
            rows.append(f"  ({race}, 10, {r[2]}, {r[3]})")
    w(",\n".join(rows) + ";")
    w("")

    w("-- Action bar: attack, racials and item buttons (class spell buttons dropped).")
    w("INSERT INTO `playercreateinfo_action` (`race`, `class`, `button`, `action`, `type`) VALUES")
    rows = []
    for race in RACES:
        src = SOURCE_CLASS[race]
        drop = SOURCE_CLASS_SPELLS[src]
        for r in act[(race, src)]:
            button, action, typ = int(r[2]), int(r[3]), int(r[4])
            if typ == 0 and action in drop:
                continue
            rows.append(f"  ({race}, 10, {button}, {action}, {typ})")
    w(",\n".join(rows) + ";")
    w("")

    text = "\n".join(out) + "\n"
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    sys.exit(main())
