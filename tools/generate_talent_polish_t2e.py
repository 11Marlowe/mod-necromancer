def sql_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def yaml_string(value: str) -> str:
    return json.dumps(value)


def emit_world_sql(path: Path) -> None:
    lines: list[str] = []
    w = lines.append
    w("-- FILE: 20261022160000_world.sql")
    w("-- Necromancer T2e active-talent polish: canonical tooltips/ranks/levels")
    w("-- and icons for the 14 active talent spells, plus an idempotent trainer")
    w("-- cleanup.  Generated by tools/generate_talent_polish_t2e.py; re-runnable.")
    w("")
    for spell_id, name, rank, level, icon, desc, aura in ACTIVE_SPELLS:
        w(
            "UPDATE `spell_template` SET "
            f"`name` = {sql_string(name)}, "
            f"`nameSubtext` = {sql_string(rank)}, "
            f"`description` = {sql_string(desc)}, "
            f"`auraDescription` = {sql_string(aura)}, "
            f"`spellIconId` = {icon}, "
            f"`baseLevel` = {level}, "
            f"`spellLevel` = {level} "
            f"WHERE `entry` = {spell_id};"
        )
    w("")
    w("-- Active talents are talent-granted, not trainer-taught.  T1 removed the")
    w("-- rows; repeat the delete so the cleanup survives a generator rerun.")
    from generate_trainers import LEARN_SPELL_BASE, TALENT_GATED, TRAINABLE
    learn_ids = [
        LEARN_SPELL_BASE + i
        for i, (spell_id, _, _) in enumerate(TRAINABLE)
        if spell_id in TALENT_GATED
    ]
    w("DELETE FROM `npc_trainer` WHERE `spell` IN ("
      + ", ".join(map(str, learn_ids)) + ");")
    w("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def emit_character_sql(path: Path) -> None:
    ids = ", ".join(map(str, ARMOR_PASSIVES))
    lines: list[str] = []
    w = lines.append
    w("-- FILE: 20261022160000_char.sql")
    w("-- Necromancer T2e legacy cleanup marker.  Characters that still hold the")
    w("-- trainer-taught armor passives are marked; the module removes them with")
    w("-- Player::RemoveSpell (OnForgotSpell skill/gear cleanup) and grants one")
    w("-- free talent reset.  Generated by tools/generate_talent_polish_t2e.py;")
    w("-- re-runnable.")
    w("")
    w(f"-- 1) mark the pre-T1 characters (module reads variable type {CLEANUP_VARIABLE})")
    w("INSERT IGNORE INTO `character_variables` (`lowGuid`, `variableType`, `value`)")
    w(f"SELECT DISTINCT cs.guid, {CLEANUP_VARIABLE}, '1'")
    w("FROM `character_spell` cs")
    w("JOIN `characters` c ON c.guid = cs.guid")
    w("WHERE c.class = 10 AND cs.spell IN (" + ids + ");")
    w("")
    w("-- 2) grant the free talent reset up front; ResetTalents will consume it")
    w("INSERT INTO `character_variables` (`lowGuid`, `variableType`, `value`)")
    w("SELECT DISTINCT cs.guid, " + str(FREE_RESET_VARIABLE) + ", '1'")
    w("FROM `character_spell` cs")
    w("JOIN `characters` c ON c.guid = cs.guid")
    w("WHERE c.class = 10 AND cs.spell IN (" + ids + ")")
    w("ON DUPLICATE KEY UPDATE `value` = "
      "IF(CAST(`value` AS UNSIGNED) < 1, '1', `value`);")
    w("")
    w("-- 3) stale action-bar and dual-spec copies of the stripped passives")
    w("DELETE csd FROM `character_spell_dual_spec` csd")
    w(f"JOIN `character_variables` v ON v.lowGuid = csd.guid AND v.variableType = {CLEANUP_VARIABLE}")
    w("WHERE csd.spell IN (" + ids + ");")
    w("")
    w("DELETE ca FROM `character_action` ca")
    w(f"JOIN `character_variables` v ON v.lowGuid = ca.guid AND v.variableType = {CLEANUP_VARIABLE}")
    w("WHERE ca.type = 0 AND ca.action IN (" + ids + ");")
    w("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def emit_client_yaml(path: Path) -> None:
    lines: list[str] = []
    w = lines.append
    w("# Talent polish T2e - generated by tools/generate_talent_polish_t2e.py.")
    w("# Canonical names/ranks/levels/tooltips/icons for the 14 active talents.")
    w("# Loads after 49b-talent-mechanics-t2d.yaml.")
    w("")
    w("Spell.dbc:")
    for spell_id, name, rank, level, icon, desc, aura in ACTIVE_SPELLS:
        w("  - type: update")
        w(f"    key: {spell_id}")
        w("    values:")
        for i in range(8):
            w(f"      Name_lang_{i}: {yaml_string(name)}")
        for i in range(8):
            w(f"      NameSubtext_lang_{i}: {yaml_string(rank)}")
        for i in range(8):
            w(f"      Description_lang_{i}: {yaml_string(desc)}")
        for i in range(8):
            w(f"      AuraDescription_lang_{i}: {yaml_string(aura)}")
        w(f"      SpellIconID: {icon}")
        w(f"      BaseLevel: {level}")
        w(f"      SpellLevel: {level}")
    w("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def apply_sql(mariadb: Path, port: str, world_sql: Path, char_sql: Path) -> None:
    for db, script in (("tw_world", world_sql), ("tw_char", char_sql)):
        subprocess.run(
            [str(mariadb), f"--port={port}", "-u", "root", db],
            input=script.read_text(encoding="utf-8"),
            text=True,
            check=True,
        )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mariadb", default=str(DEFAULT_MARIADB))
    ap.add_argument("--port", default="3307")
    ap.add_argument("--apply", action="store_true",
                    help="apply the generated world/character SQL")
    args = ap.parse_args()

    out_world = MODULE_DIR / "data/sql/world/20261022160000_world.sql"
    out_char = MODULE_DIR / "data/sql/character/20261022160000_char.sql"
    out_yaml = MODULE_DIR / "client/patches/49c-talent-polish-t2e.yaml"

    emit_world_sql(out_world)
    emit_character_sql(out_char)
    emit_client_yaml(out_yaml)

    if args.apply:
        apply_sql(Path(args.mariadb), args.port, out_world, out_char)

    print(f"active talent spells: {len(ACTIVE_SPELLS)}")
    print(f"wrote {out_world}")
    print(f"wrote {out_char}")
    print(f"wrote {out_yaml}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
