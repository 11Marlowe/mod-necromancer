#!/usr/bin/env python3
"""Generate the Necromancer gate-item batch (backlog G2 + G3).

The design gates two Raise spells behind books that drop from dungeon bosses:

  G2  Raise Bloodmage (61038)  <- Amnennar the Coldbringer (7358), 10%
  G3  Raise Wight     (61040)  <- Darkmaster Gandling (1853), 5%
                                 (and "requires Raise Abomination learned",
                                  implemented with item_template.required_spell)

Both spells are trainer-taught today, so this batch also removes their
`npc_trainer` rows (learn spells 61125 and 61130).  The learn-spell wrappers
themselves stay: the items use them as their on-use spell, and they already
have client `Spell.dbc` rows, so **no client patch is needed** for this batch
(items in 1.12 are server data; only display_id must exist in the client).

G1 (the L10 Death Knight chain) and G5 (retiring the placeholder quests) are
deliberately NOT touched - the placeholder quests stay for now.

Outputs:
  data/sql/world/20261023180000_world.sql

Usage:
  python tools/generate_gate_items.py
"""

import argparse
import subprocess
import sys

SQL_FILE = "20261023180000_world.sql"

DEFAULT_MARIADB = r"C:\Users\gawrg\Desktop\TurtleTest\server\mariadb-portable\bin\mariadb.exe"

CLASS_MASK_NECROMANCER = 0x200

# (item id, name, description, learn spell, required spell, required level)
ITEMS = [
    dict(id=63104, name="Tome of the Bloodmage",
         desc="Bound in cold vellum, this tome reeks of the crypt.  "
              "Reading it teaches the secret of raising a Bloodmage.",
         learn_spell=61125,          # learn wrapper -> Raise Bloodmage 61038
         taught_spell=61038,
         required_spell=0,
         required_level=38),
    dict(id=63105, name="Codex of the Wight",
         desc="Gandling's notes on the greater dead.  Only a necromancer "
              "who can already raise an Abomination can master it.",
         learn_spell=61130,          # learn wrapper -> Raise Wight 61040
         taught_spell=61040,
         required_spell=61039,       # design: requires Raise Abomination learned
         required_level=58),
]

# (boss entry, boss name, item id, chance)
LOOT = [
    (7358, "Amnennar the Coldbringer", 63104, 10.0),
    (1853, "Darkmaster Gandling", 63105, 5.0),
]

# npc_trainer rows to remove (the learn-spell wrappers themselves survive)
TRAINER_LEARN_IDS = [61125, 61130]


def run(mariadb, port, sql, db="tw_world"):
    out = subprocess.run(
        [mariadb, f"--port={port}", "-u", "root", db,
         "--batch", "--skip-column-names", "-e", sql],
        capture_output=True, text=True, check=True,
    )
    return [line.split("\t") for line in out.stdout.splitlines() if line.strip()]


def sql_literal(value, data_type):
    if data_type in ("tinyint", "smallint", "mediumint", "int", "bigint",
                     "float", "double", "decimal"):
        return str(value)
    escaped = str(value).replace("\\", "\\\\").replace("'", "''")
    return f"'{escaped}'"


def table_columns(mariadb, port, table):
    rows = run(mariadb, port,
               "SELECT COLUMN_NAME, DATA_TYPE FROM information_schema.columns "
               f"WHERE table_schema='tw_world' AND table_name='{table}' "
               "ORDER BY ORDINAL_POSITION")
    return [r[0] for r in rows], {r[0]: r[1] for r in rows}


def clone_row(mariadb, port, table, entry):
    rows = run(mariadb, port, f"SELECT * FROM {table} WHERE entry = {entry}")
    if len(rows) != 1:
        raise RuntimeError(f"{table}: model {entry} not found")
    return rows[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mariadb", default=DEFAULT_MARIADB)
    ap.add_argument("--port", default="3307")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    item_cols, item_types = table_columns(args.mariadb, args.port, "item_template")
    idx = {c: i for i, c in enumerate(item_cols)}

    out = []
    w = out.append
    w("-- FILE: %s" % SQL_FILE)
    w("-- Necromancer (class 10) gate-item batch (2026-10-23): backlog G2 + G3.")
    w("--")
    w("--  G2 Tome of the Bloodmage (63104) - 10% from Amnennar the Coldbringer")
    w("--     (Razorfen Downs, entry 7358); teaches Raise Bloodmage (61038).")
    w("--  G3 Codex of the Wight (63105) - 5% from Darkmaster Gandling")
    w("--     (Scholomance, entry 1853); teaches Raise Wight (61040) and")
    w("--     requires Raise Abomination (61039) via required_spell.")
    w("--")
    w("-- Both spells stop being trainer-taught (npc_trainer rows removed); the")
    w("-- learn-spell wrappers 61125/61130 stay and double as the items'")
    w("-- on-use spells.  Server-side only - no client patch.")
    w("-- Generated by tools/generate_gate_items.py; re-runnable.")
    w("")
    w("DELETE FROM `item_template` WHERE `entry` IN (%s);" %
      ", ".join(str(i["id"]) for i in ITEMS))
    w("DELETE FROM `creature_loot_template` WHERE `entry` = 7358 AND `item` = 63104;")
    w("DELETE FROM `creature_loot_template` WHERE `entry` = 1853 AND `item` = 63105;")
    w("DELETE FROM `npc_trainer` WHERE `spell` IN (%s);" %
      ", ".join(str(s) for s in TRAINER_LEARN_IDS))
    w("")

    # ---- items: clone the Corpse Bag item scaffold and override ----
    for item in ITEMS:
        values = list(clone_row(args.mariadb, args.port, "item_template", 63100))
        values[idx["entry"]] = str(item["id"])
        values[idx["name"]] = item["name"]
        values[idx["description"]] = item["desc"]
        overrides = {
            "class": 9,                 # Recipe
            "subclass": 0,              # Book
            "display_id": 1246,         # vanilla book art (exists in the client)
            "quality": 3,
            "flags": 0,
            "buy_price": 0,
            "sell_price": 0,
            "inventory_type": 0,
            "allowable_class": CLASS_MASK_NECROMANCER,
            "allowable_race": -1,
            "item_level": item["required_level"],
            "required_level": item["required_level"],
            "required_spell": item["required_spell"],
            "max_count": 1,
            "stackable": 1,
            "bonding": 1,               # bind on pickup
            "material": 0,
            "spellid_1": item["learn_spell"],
            "spelltrigger_1": 0,        # on use
            "spellcharges_1": -1,       # negative = expendable: the core destroys the item after use
            "spellcooldown_1": -1,
            "spellcategory_1": 0,
            "spellcategorycooldown_1": -1,
            "duration": 0,
        }
        for column, value in overrides.items():
            values[idx[column]] = str(value)
        literals = [sql_literal(v, item_types[c]) for v, c in zip(values, item_cols)]
        w("-- %s (teaches %d)" % (item["name"], item["taught_spell"]))
        w("INSERT INTO `item_template` (`%s`) VALUES" % "`, `".join(item_cols))
        w("  (%s);" % ", ".join(literals))
        w("")

    # ---- loot ----
    w("-- boss drops")
    for entry, boss, item_id, chance in LOOT:
        w("-- %s (%d) -> %d at %g%%" % (boss, entry, item_id, chance))
        w("INSERT INTO `creature_loot_template` "
          "(`entry`, `item`, `ChanceOrQuestChance`, `groupid`, `mincountOrRef`, "
          "`maxcount`, `condition_id`)")
        w("  VALUES (%d, %d, %g, 0, 1, 1, 0);" % (entry, item_id, chance))
    w("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    print(f"wrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
