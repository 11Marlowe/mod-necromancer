#!/usr/bin/env python3
"""Generate the Necromancer Phase-2 spell SQL (server side) from an existing DB.

Batch 1 copies the full `spell_template` rows of vanilla model spells under new
IDs, adds the rank chains, registers the spells under the new "Necromancy"
skill line (700, class mask 512), grants the rank-1 spells at creation and
places them on the action bar.  Higher ranks and Death Coil are learned by the
module when the player reaches the level (see src/mod_necromancer.cpp).

Usage:
  python tools/generate_phase2_spells.py --out data/sql/world/20261014160000_world.sql
"""

import argparse
import subprocess
import sys

# new spell id -> model spell id copied from spell_template
NEW_SPELLS = [
    (61010, 686),    # Plague Bolt Rank 1   <- Shadow Bolt
    (61011, 695),    # Plague Bolt Rank 2
    (61012, 705),    # Plague Bolt Rank 3
    (61013, 2973),   # Reap Rank 1          <- Raptor Strike (mana melee strike)
    (61014, 14260),  # Reap Rank 2
    (61015, 168),    # Bone Armor           <- Frost Armor
]

# (spell_id, prev_spell, first_spell, rank)
SPELL_CHAIN = [
    (61010, 0, 61010, 1),
    (61011, 61010, 61010, 2),
    (61012, 61011, 61010, 3),
    (61013, 0, 61013, 1),
    (61014, 61013, 61013, 2),
]

# spell -> learn_on_get_skill value (copied from the model's own row)
LEARN_ON_GET = {61010: 2, 61011: 0, 61012: 0, 61013: 2, 61014: 0, 61015: 2, 6789: 0}

# Server-side display name/rank overrides (spell_template name columns; the
# client reads its own Spell.dbc patch instead).
NAME_OVERRIDES = {
    61010: ("Plague Bolt", "Rank 1"),
    61011: ("Plague Bolt", "Rank 2"),
    61012: ("Plague Bolt", "Rank 3"),
    61013: ("Reap", "Rank 1"),
    61014: ("Reap", "Rank 2"),
    61015: ("Bone Armor", ""),
}

RACES = list(range(1, 11))
START_SPELLS = [(61010, "Plague Bolt"), (61013, "Reap"), (61015, "Bone Armor")]
ACTION_BUTTONS = [(1, 61010), (2, 61013), (5, 61015)]

SKILL_LINE = 700          # "Necromancy"
CLASS_MASK = 512          # class 10
DEATH_COIL = 6789


def run(mariadb, port, sql):
    out = subprocess.run(
        [mariadb, f"--port={port}", "-u", "root", "tw_world",
         "--batch", "--skip-column-names", "-e", sql],
        capture_output=True, text=True, check=True,
    )
    return [line.split("\t") for line in out.stdout.splitlines() if line.strip()]


def sql_literal(value, data_type):
    if value == "NULL":
        return "NULL"
    if data_type in ("tinyint", "smallint", "mediumint", "int", "bigint",
                     "float", "double", "decimal"):
        return value
    escaped = value.replace("\\", "\\\\").replace("'", "''")
    return f"'{escaped}'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mariadb", default=r"C:\Users\gawrg\Desktop\TurtleTest\server\mariadb-portable\bin\mariadb.exe")
    ap.add_argument("--port", default="3307")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    columns = run(args.mariadb, args.port,
                  "SELECT COLUMN_NAME, DATA_TYPE FROM information_schema.columns "
                  "WHERE table_schema='tw_world' AND table_name='spell_template' "
                  "ORDER BY ORDINAL_POSITION")
    col_names = [c[0] for c in columns]
    col_types = {c[0]: c[1] for c in columns}
    entry_idx = col_names.index("entry")

    print(f"spell_template: {len(col_names)} columns", file=sys.stderr)

    out = []
    w = out.append
    w("-- FILE: 20261014160000_world.sql")
    w("-- Necromancer (class 10) Phase 2 batch 1: Plague Bolt R1-3, Reap R1-2,")
    w("-- Bone Armor.  Generated by tools/generate_phase2_spells.py; re-runnable.")
    w("-- Spell rows are full copies of the model spells' spell_template rows;")
    w("-- names/ranks/tooltips come from the client Spell.dbc patch (patch-Z.mpq).")
    w("")

    model_ids = sorted({m for _, m in NEW_SPELLS})
    new_ids = [n for n, _ in NEW_SPELLS]
    w("DELETE FROM `spell_template` WHERE `entry` IN (%s);" %
      ", ".join(str(i) for i in new_ids))
    w("DELETE FROM `spell_chain` WHERE `spell_id` IN (%s);" %
      ", ".join(str(i) for i in new_ids))
    w("DELETE FROM `skill_line_ability` WHERE `skill_id` = %d;" % SKILL_LINE)
    w("DELETE FROM `playercreateinfo_spell` WHERE `class` = 10 AND `spell` IN (61010, 61013, 61015);")
    w("DELETE FROM `playercreateinfo_action` WHERE `class` = 10 AND `button` IN (1, 2, 5);")
    w("")

    w("-- ============================================================")
    w("-- spell_template rows (copies of the model spells, new entry ids)")
    w("-- ============================================================")
    for new_id, model_id in NEW_SPELLS:
        rows = run(args.mariadb, args.port,
                   f"SELECT * FROM spell_template WHERE entry = {model_id}")
        if len(rows) != 1:
            print(f"ERROR: model {model_id} not found", file=sys.stderr)
            return 1
        values = list(rows[0])
        values[entry_idx] = str(new_id)
        name, rank = NAME_OVERRIDES.get(new_id, (None, None))
        if name is not None:
            values[col_names.index("name")] = name
            values[col_names.index("nameSubtext")] = rank
        literals = [sql_literal(v, col_types[c]) for v, c in zip(values, col_names)]
        w("INSERT INTO `spell_template` (`%s`) VALUES" % "`, `".join(col_names))
        w("  (%s);" % ", ".join(literals))
        w("")

    w("-- ============================================================")
    w("-- spell chains (ranks)")
    w("-- ============================================================")
    w("INSERT INTO `spell_chain` (`spell_id`, `prev_spell`, `first_spell`, `rank`, `req_spell`) VALUES")
    w(",\n".join(f"  ({s}, {p}, {f}, {r}, 0)" for s, p, f, r in SPELL_CHAIN) + ";")
    w("")

    w("-- ============================================================")
    w("-- skill_line_ability rows (Necromancy, class mask 512)")
    w("-- ============================================================")
    next_id = int(run(args.mariadb, args.port,
                      "SELECT IFNULL(MAX(`id`), 0) + 1 FROM skill_line_ability")[0][0])
    w("INSERT INTO `skill_line_ability` (`id`, `skill_id`, `spell_id`, `race_mask`, `class_mask`, "
      "`req_skill_value`, `superseded_by_spell`, `learn_on_get_skill`, `max_value`, `min_value`, "
      "`req_train_points`) VALUES")
    rows = []
    for spell_id in new_ids + [DEATH_COIL]:
        rows.append(f"  ({next_id}, {SKILL_LINE}, {spell_id}, 0, {CLASS_MASK}, 1, 0, "
                    f"{LEARN_ON_GET.get(spell_id, 0)}, 0, 0, 0)")
        next_id += 1
    w(",\n".join(rows) + ";")
    w("")

    w("-- ============================================================")
    w("-- starting spells + action bar for every race")
    w("-- ============================================================")
    w("INSERT INTO `playercreateinfo_spell` (`race`, `class`, `spell`, `note`) VALUES")
    rows = []
    for race in RACES:
        for spell_id, note in START_SPELLS:
            rows.append(f"  ({race}, 10, {spell_id}, '{note}')")
    w(",\n".join(rows) + ";")
    w("")

    w("INSERT INTO `playercreateinfo_action` (`race`, `class`, `button`, `action`, `type`) VALUES")
    rows = []
    for race in RACES:
        for button, spell_id in ACTION_BUTTONS:
            rows.append(f"  ({race}, 10, {button}, {spell_id}, 0)")
    w(",\n".join(rows) + ";")
    w("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
